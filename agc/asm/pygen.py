"""Generate Python modules from an assembled AGC program.

For every ``.agc`` source file one ``.py`` module is written.  The module
mirrors the original listing line by line: full-line comments are kept as
Python comments, every assembled word becomes a ``W(...)`` call and every
symbol definition (ERASE / EQUALS / =) a ``S(...)`` call.  The result is a
Python package that can be imported without the assembler: the emulator
builds the rope from it, and the test UI uses it for symbolic display.
"""

from __future__ import annotations

import keyword
import re
from pathlib import Path

from .assembler import AssemblyResult, LineRecord, NUM_FIXED_BANKS
from .address import Address

HEADER = '''"""{source} -- {title}

Converted from {relsrc} by agc2py (the Apollo 11 AGC -> Python converter).
Pages {pages} of the original program listing.

Every ``W(address, word, label, operator, operand, comment)`` line is one
15-bit word of the AGC rope memory; ``S(name, kind, value)`` defines a symbol.
Original comments are preserved as Python comments.
"""

from agc.program import Module

MODULE = Module({name!r}, {source!r}, {program!r}, pages={pages!r})
W = MODULE.W
S = MODULE.S

'''

INIT_TEMPLATE = '''"""{title} -- Python conversion of the AGC flight software.

Generated by agc2py from {relsrc}.
Load it with ``agc.program.load_program({pkgname!r})``.
"""

NAME = {name!r}
TITLE = {title!r}
SOURCE_DIR = {relsrc!r}
MODULES = [
{modules}]
'''

PROGRAM_TITLES = {
    "Luminary099": "Luminary 1A (build 099), Apollo 11 Lunar Module guidance computer",
    "Comanche055": "Comanche (build 055), Apollo 11 Command Module guidance computer",
}


def module_pyname(agc_file: str) -> str:
    """``BURN_BABY_BURN--MASTER_IGNITION_ROUTINE.agc`` -> ``BURN_BABY_BURN__MASTER_IGNITION_ROUTINE``."""
    base = agc_file[:-4] if agc_file.lower().endswith(".agc") else agc_file
    name = re.sub(r"[^0-9A-Za-z_]", "_", base)
    if name[0].isdigit():
        name = "M_" + name
    if keyword.iskeyword(name):
        name += "_"
    return name


def _q(s: str) -> str:
    return repr(s)


def _page_range(lines: list[LineRecord]) -> str:
    pages = []
    for ln in lines:
        m = re.match(r"\s*#+\s*Page\s+(\d+)", ln.text)
        if m:
            pages.append(int(m.group(1)))
    if not pages:
        return ""
    return f"{min(pages)}-{max(pages)}" if min(pages) != max(pages) else str(min(pages))


def _symbol_kind(rec: LineRecord) -> str | None:
    op = rec.operator
    if op == "ERASE":
        return "erase"
    if op in ("EQUALS", "=", "=MINUS"):
        return "equals"
    return None


def generate(result: AssemblyResult, program: str, src_dir: Path, out_dir: Path,
             rel_src: str) -> list[str]:
    """Write the package; returns the list of module names in MAIN.agc order."""
    out_dir.mkdir(parents=True, exist_ok=True)
    title = PROGRAM_TITLES.get(program, program)

    # Group listing records by file, in include order.
    by_file: dict[str, list[LineRecord]] = {}
    order: list[str] = []
    for rec in result.lines:
        if rec.file not in by_file:
            by_file[rec.file] = []
            order.append(rec.file)
        by_file[rec.file].append(rec)

    module_names = []
    for fname in order:
        recs = by_file[fname]
        modname = module_pyname(fname)
        module_names.append(modname)
        text = render_module(recs, fname, modname, program, title, rel_src, result)
        (out_dir / f"{modname}.py").write_text(text, encoding="utf-8")

    # Bank checksums are not in the source; they are produced by the assembler.
    module_names.append("ROPE_CHECKSUMS")
    (out_dir / "ROPE_CHECKSUMS.py").write_text(render_checksums(result, program, title, rel_src), encoding="utf-8")

    modules = "".join(f"    {m!r},\n" for m in module_names)
    (out_dir / "__init__.py").write_text(
        INIT_TEMPLATE.format(title=title, relsrc=rel_src, pkgname=program.lower(),
                             name=program, modules=modules),
        encoding="utf-8",
    )
    return module_names


def render_checksums(result: AssemblyResult, program: str, title: str, rel_src: str) -> str:
    out = [HEADER.format(source="(generated)", title=title, relsrc=rel_src, pages="",
                         name="ROPE_CHECKSUMS", program=program)]
    out.append("# Bank identification words and bugger words (bank checksums).  The AGC\n"
               "# self-check sums each bank; the bugger word makes the sum equal to the\n"
               "# bank number.  These words are generated by the assembler, not written\n"
               "# by the programmers, which is why they have no source lines.\n\n")
    for bank in range(NUM_FIXED_BANKS):
        if bank not in result.bugger_words:
            continue
        offset, bugger = result.bugger_words[bank]
        # the id words directly precede the bugger word if the assembler placed them
        start = result.bank_counts[bank]
        for off in range(start, offset):
            w = result.fixed[bank][off]
            out.append(f"W({_q(_fmt_addr(bank, off))}, 0o{w:05o}, '', 'BANKID', '', 'bank id word', kind='data')\n")
        out.append(f"W({_q(_fmt_addr(bank, offset))}, 0o{bugger:05o}, '', 'BNKSUM', '{bank:02o}', "
                   f"'bugger word for bank {bank:02o}', kind='data')\n")
    return "".join(out)


def _fmt_addr(bank: int, offset: int) -> str:
    if bank in (2, 3):
        return f"{bank * 0o2000 + offset:04o}"
    return f"{bank:02o},{0o2000 + offset:04o}"


def _addr_of(pc: Address) -> str | None:
    bank = pc.bank_number()
    if bank is None:
        return None
    return _fmt_addr(bank, pc.fixed_offset())


def _clean_comment(c: str) -> str:
    c = c.rstrip()
    return c[1:] if c.startswith(" ") else c


def render_module(recs: list[LineRecord], fname: str, modname: str, program: str,
                  title: str, rel_src: str, result: AssemblyResult) -> str:
    pages = _page_range(recs)
    out = [HEADER.format(source=fname, title=title, relsrc=f"{rel_src}/{fname}", pages=pages,
                         name=modname, program=program)]
    blank_pending = False
    for rec in recs:
        stripped = rec.text.strip()
        if stripped == "":
            blank_pending = True
            continue
        if stripped.startswith("#"):
            if blank_pending:
                out.append("\n")
                blank_pending = False
            out.append("# " + stripped.lstrip("#").strip() + "\n" if stripped.strip("#").strip() else "#\n")
            continue
        if blank_pending:
            out.append("\n")
            blank_pending = False

        comment = _clean_comment(rec.comment)
        skind = _symbol_kind(rec)
        if rec.words and rec.pc is not None and rec.pc.fixed and not rec.pc.invalid:
            addr = _addr_of(rec.pc)
            operand = rec.operand
            if rec.mod1:
                operand = f"{operand} {rec.mod1}"
            if rec.mod2:
                operand = f"{operand} {rec.mod2}"
            kind = rec.kind or "data"
            for i, w in enumerate(rec.words):
                a = addr if i == 0 else _fmt_addr(rec.pc.bank_number(), rec.pc.fixed_offset() + i)
                label = rec.label if i == 0 else ""
                op = rec.operator if i == 0 else ""
                opnd = operand if i == 0 else ""
                cmt = comment if i == 0 else ""
                parts = [_q(a), f"0o{w:05o}"]
                tail = [label, op, opnd, cmt]
                while tail and tail[-1] == "":
                    tail.pop()
                parts += [_q(t) for t in tail]
                extra = ""
                if kind != "basic":
                    extra = f", kind={_q(kind)}"
                out.append(f"W({', '.join(parts)}{extra}, line={rec.line})\n")
            if rec.error:
                out.append(f"#   ^^^ assembler: {rec.error}\n")
            continue
        if rec.label and skind:
            sym = result.symbols.get(rec.label)
            if sym is not None and not sym.value.invalid:
                v = sym.value
                if v.constant and not v.address:
                    kind, value = "constant", v.value
                else:
                    kind, value = skind, v.value
                cmt = f", comment={_q(comment)}" if comment else ""
                out.append(f"S({_q(rec.label)}, {_q(kind)}, 0o{value & 0o7777777:o}, line={rec.line}){'  # ' + comment if comment else ''}\n")
            continue
        if rec.label and rec.pc is not None and not rec.pc.invalid:
            # a label on a line without words (e.g. before a BANK or on a lone label)
            v = result.symbols.get(rec.label)
            if v is not None and not v.value.invalid:
                kind = "label" if v.value.fixed else ("erase" if v.value.erasable else "constant")
                out.append(f"S({_q(rec.label)}, {_q(kind)}, 0o{v.value.value & 0o7777777:o}, line={rec.line})\n")
            continue
        # pseudo-ops that produce no words: keep them as comments for orientation
        if rec.operator:
            pieces = [rec.operator, rec.operand, rec.mod1, rec.mod2]
            txt = " ".join(p for p in pieces if p)
            out.append(f"#   {rec.label + ' ' if rec.label else ''}{txt}{('  # ' + comment) if comment else ''}\n")
    # register symbols that were defined in this file but have no textual line (safety net)
    return "".join(out)
